def benchmark_model(
    model_name,
    prompt="Explain how a CNC machine works.",
    max_new_tokens=100,
):
    print(f"Loading {model_name}")

    if torch.cuda.is_available():
        torch.cuda.empty_cache()
        torch.cuda.reset_peak_memory_stats()

    tokenizer = AutoTokenizer.from_pretrained(model_name)

    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        dtype="auto",
        device_map="auto",
    )

    model.eval()

    messages = [
        {"role": "user", "content": prompt}
    ]

    formatted_prompt = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
    )

    input_device = next(model.parameters()).device

    inputs = tokenizer(
        formatted_prompt,
        return_tensors="pt",
    ).to(input_device)

    input_tokens = inputs["input_ids"].shape[1]

    # Short warm-up generation
    with torch.inference_mode():
        model.generate(
            **inputs,
            max_new_tokens=5,
            do_sample=False,
            use_cache=True,
        )

    if torch.cuda.is_available():
        torch.cuda.synchronize()
        torch.cuda.reset_peak_memory_stats()

    start = time.perf_counter()

    with torch.inference_mode():
        outputs = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=False,
            use_cache=True,
        )

    if torch.cuda.is_available():
        torch.cuda.synchronize()

    elapsed = time.perf_counter() - start
    generated_tokens = outputs.shape[1] - input_tokens
    tokens_per_second = generated_tokens / elapsed

    parameter_count = sum(
        parameter.numel()
        for parameter in model.parameters()
    )

    peak_memory_gb = (
        torch.cuda.max_memory_allocated() / 1e9
        if torch.cuda.is_available()
        else 0
    )

    generated_text = tokenizer.decode(
        outputs[0, input_tokens:],
        skip_special_tokens=True,
    )

    result = {
        "Parameters": parameter_count,
        "Generated tokens": generated_tokens,
        "Seconds": elapsed,
        "Tokens/sec": tokens_per_second,
        "Peak GPU memory (GB)": peak_memory_gb,
    }

    del outputs, inputs, model, tokenizer
    gc.collect()

    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    return result, generated_text


