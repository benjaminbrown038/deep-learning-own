models_to_test = ["0.5B", "1.5B", "3B"]

benchmark_results = []

for size in models_to_test:
    try:
        result, _ = benchmark_model(models[size])

        benchmark_results.append({
            "Model": size,
            **result,
        })

    except torch.cuda.OutOfMemoryError:
        print(f"{size} did not fit in GPU memory.")

        gc.collect()
        torch.cuda.empty_cache()

